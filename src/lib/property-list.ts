import type {Property} from '@/types'
import {isTierExpired} from '@/utils/premium-helper'

/**
 * Показывать ли объявление в списках прямо сейчас.
 *
 * Статус `inactive` объявлению проставляет ночная функция `expirePaidTiers`, и
 * между окончанием тарифа и её прогоном проходит до суток. Всё это время
 * объявление формально `active` — то есть выборки его брали, и оно висело на
 * витрине уже после того, как оплаченный срок кончился.
 *
 * Здесь та же проверка делается по дате, в момент показа: истёкшее уходит с
 * витрины сразу. Ночная функция после этого лишь закрепляет положение в базе,
 * проставляя `status` и `expiredAt`.
 *
 * Обычный тариф не истекает — `isTierExpired` для него всегда ложь.
 */
export function isOnDisplay(property: Pick<Property, 'status' | 'listingTier' | 'premiumExpiresAt' | 'vipExpiresAt'>): boolean {
  if (property.status && property.status !== 'active') return false
  return !isTierExpired(property)
}

/**
 * Убирает из объявления то, что нужно только на его собственной странице.
 *
 * Списки — главная, разделы регионов, блок похожих — отдают клиенту по три
 * десятка объявлений целиком, вместе с описанием на трёх языках и всей веткой
 * комментариев. Это уезжает в браузер дважды: разметкой и потоком RSC, из
 * которого React восстанавливает состояние. На главной так набегала половина
 * веса страницы, а прочитать эти поля в списке некому:
 *
 * ```
 * карточка   title, price, images, rooms, area, вместимость, rating, reviews
 * карта      coordinates
 * поиск      title, address, amenities     (описание НЕ ищется, проверено)
 * фильтры    type, district, price, rooms, гости, city, даты недоступности
 * ```
 *
 * Отдельная история — `owner`. Там имя, телефон и почта владельца, и они
 * уезжали в открытый HTML главной по одному комплекту на объявление: три
 * десятка чужих контактов на странице, которую видит любой сборщик. Показывать
 * их список и не собирался — контакты нужны на странице самого объявления, там
 * они и остаются. Так что это не только про вес.
 *
 * Поля не выкидываются, а обнуляются: тип `Property` остаётся честным по форме,
 * и если что-то однажды всё же прочитает описание в списке, оно увидит пустую
 * строку, а не упадёт. Полный документ никуда не делся — страница объявления
 * берёт его отдельным запросом `getProperty`.
 *
 * Ограничивать выборку в Firestore через `select` было бы соблазнительно, но
 * это список разрешённых полей: забыл одно — и молча ломается фильтр. Здесь
 * перечислено ровно то, что убираем.
 */
export function toListItem<T extends Property>(property: T): T {
  return {
    ...property,
    description: {az: '', en: '', ru: ''},
    comments: [],
    owner: {name: '', phone: '', email: ''}
  }
}
